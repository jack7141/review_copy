export async function POST(req: Request) {
  const { reviews, documentType, productName, targetCustomer, tone, bannedWords, evidenceStrength } = await req.json();

  if (!reviews || !documentType) {
    return new Response("Missing required fields", { status: 400 });
  }

  const docConfig = DOCUMENT_TYPES[documentType as keyof typeof DOCUMENT_TYPES];
  if (!docConfig) {
    return new Response("Invalid document type", { status: 400 });
  }

  // reviews is a string joined by \n from the client
  const reviewLines = (typeof reviews === "string" ? reviews.split("\n") : reviews) as string[];
  const formattedReviews = reviewLines
    .map((r: string, i: number) => `후기 #${i + 1}: ${r.trim()}`)
    .filter((r: string) => r.length > 10)
    .join("\n\n");

  const toneDescription = tone ? TONE_DESCRIPTIONS[tone as keyof typeof TONE_DESCRIPTIONS] : "";
  const strengthDescription = evidenceStrength
    ? EVIDENCE_STRENGTH[evidenceStrength as keyof typeof EVIDENCE_STRENGTH]
    : EVIDENCE_STRENGTH.conservative;

  const contextParts: string[] = [];

  if (productName) contextParts.push(`제품/서비스명: ${productName}`);
  if (targetCustomer) contextParts.push(`타겟 고객: ${targetCustomer}`);
  if (toneDescription) contextParts.push(`작성 톤: ${toneDescription}`);
  if (bannedWords) contextParts.push(`추가 금칙어(절대 사용 금지): ${bannedWords}`);
  contextParts.push(`증거 추출 강도: ${strengthDescription}`);

  const additionalContext = `\n\n## 추가 정보\n${contextParts.join("\n")}`;

  const result = streamText({
    model: openai("gpt-4o"),
    system: docConfig.prompt + additionalContext,
    messages: [
      {
        role: "user",
        content: `다음 고객 후기들을 분석하여 ${docConfig.name}를 작성해주세요:\n\n${formattedReviews}`,
      },
    ],
  });

  return result.toTextStreamResponse();
}
